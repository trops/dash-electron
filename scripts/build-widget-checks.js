#!/usr/bin/env node
/**
 * build-widget-checks.js — bundles the Widget Builder's checks
 * (src/AiAssistant/widgetChecksEntry.js) into public/lib/widgetChecks.cjs
 * for the main process (the Dash team's Checker, create-entry CRE-011).
 *
 *   node scripts/build-widget-checks.js          write the file
 *   node scripts/build-widget-checks.js --check  fail if it's out of date
 */
const fs = require("fs");
const path = require("path");
const { rollup } = require("rollup");
const { nodeResolve } = require("@rollup/plugin-node-resolve");

const ROOT = path.join(__dirname, "..");
const ENTRY = path.join(ROOT, "src", "AiAssistant", "widgetChecksEntry.js");
const OUT = path.join(ROOT, "public", "lib", "widgetChecks.cjs");
const BANNER =
    "// GENERATED by scripts/build-widget-checks.js from src/AiAssistant —\n" +
    "// do not edit. Run `node scripts/build-widget-checks.js` after changing\n" +
    "// the Widget Builder's checks.";

async function build() {
    const bundle = await rollup({
        input: ENTRY,
        plugins: [nodeResolve({ extensions: [".js"] })],
        onwarn(warning, warn) {
            if (warning.code === "CIRCULAR_DEPENDENCY") return;
            warn(warning);
        },
    });
    const { output } = await bundle.generate({
        format: "cjs",
        exports: "named",
        banner: BANNER,
    });
    await bundle.close();
    return output[0].code;
}

build()
    .then((code) => {
        if (process.argv.includes("--check")) {
            const current = fs.existsSync(OUT)
                ? fs.readFileSync(OUT, "utf8")
                : "";
            if (current !== code) {
                console.error(
                    "FAIL  public/lib/widgetChecks.cjs is out of date — run `node scripts/build-widget-checks.js`."
                );
                process.exit(1);
            }
            console.log("PASS  public/lib/widgetChecks.cjs is up to date");
            return;
        }
        fs.writeFileSync(OUT, code);
        console.log(`wrote ${path.relative(ROOT, OUT)}`);
    })
    .catch((err) => {
        console.error(err);
        process.exit(1);
    });
